import streamlit as st
import pandas as pd
import plotly.express as px
import numpy as np
import os

st.set_page_config(page_title="Zerodha AI Financial Intelligence", page_icon="📈", layout="wide")
st.title("📈 Zerodha AI Financial Intelligence Platform")
st.caption("Educational prototype • Sample portfolio data • Not investment advice")

sample = pd.DataFrame([
    {"Stock":"RELIANCE","Sector":"Energy","Quantity":10,"Buy Price":2500,"Current Price":2620},
    {"Stock":"TCS","Sector":"IT","Quantity":8,"Buy Price":3800,"Current Price":3920},
    {"Stock":"INFY","Sector":"IT","Quantity":15,"Buy Price":1450,"Current Price":1510},
    {"Stock":"HDFCBANK","Sector":"Banking","Quantity":12,"Buy Price":1600,"Current Price":1550},
    {"Stock":"ITC","Sector":"FMCG","Quantity":20,"Buy Price":420,"Current Price":445},
])

st.sidebar.header("Portfolio holdings")
st.sidebar.caption("Use this uploader only for holdings CSV.")
f = st.sidebar.file_uploader("Upload holdings CSV (optional)", type=["csv"], key="holdings")
if f:
    try:
        h = pd.read_csv(f)
        required = {"Stock","Sector","Quantity","Buy Price","Current Price"}
        if not required.issubset(h.columns):
            st.sidebar.error("Wrong format for holdings. Upload historical OHLCV data in the separate section below.")
            h = sample.copy()
    except Exception:
        h = sample.copy()
else:
    h = sample.copy()
for c in ["Quantity","Buy Price","Current Price"]:
    h[c] = pd.to_numeric(h[c], errors="coerce")
h = h.dropna(subset=["Quantity","Buy Price","Current Price"]).copy()
h["Invested"] = h["Quantity"] * h["Buy Price"]
h["Current Value"] = h["Quantity"] * h["Current Price"]
h["P&L"] = h["Current Value"] - h["Invested"]
h["Return %"] = np.where(h["Invested"] != 0, h["P&L"]/h["Invested"]*100, 0).round(2)

st.header("1. Portfolio overview")
st.caption("Illustrative sample holdings unless a valid holdings CSV is uploaded.")
inv, val, pnl = h["Invested"].sum(), h["Current Value"].sum(), h["P&L"].sum()
ret = pnl/inv*100 if inv else 0
a,b,c,d = st.columns(4)
a.metric("Invested",f"₹{inv:,.0f}")
b.metric("Current value",f"₹{val:,.0f}")
c.metric("Profit / Loss",f"₹{pnl:,.0f}",f"{ret:+.2f}%")
d.metric("Holdings",str(len(h)))
l,r=st.columns(2)
with l:
    st.plotly_chart(px.pie(h.groupby("Sector",as_index=False)["Current Value"].sum(),names="Sector",values="Current Value",hole=.4,title="Allocation by sector"),use_container_width=True)
with r:
    st.plotly_chart(px.bar(h,x="Stock",y="P&L",color="P&L",title="Profit / loss by stock"),use_container_width=True)
st.dataframe(h[["Stock","Sector","Quantity","Buy Price","Current Price","Invested","Current Value","P&L","Return %"]],use_container_width=True,hide_index=True)

st.divider()
st.header("2. Historical stock data analysis (OHLCV)")
st.write("Upload `ALL_5_STOCKS_5Y_DAILY.csv` or an individual CSV from your `stock_csv` folder.")
hist_file = st.file_uploader("Upload historical stock CSV",type=["csv"],key="history")
def norm(x):
    return str(x).strip().lower().replace(" ","_").replace("-","_")
if hist_file:
    try:
        raw=pd.read_csv(hist_file)
        cmap={norm(c):c for c in raw.columns}
        datecol=next((cmap[k] for k in ["date","datetime","timestamp"] if k in cmap),None)
        closecol=next((cmap[k] for k in ["close","adj_close","adjclose"] if k in cmap),None)
        tickercol=next((cmap[k] for k in ["ticker","symbol","stock"] if k in cmap),None)
        if datecol is None or closecol is None:
            st.error("Could not find Date and Close columns. Upload a CSV generated by the stock-data helper.")
        else:
            x=raw.copy()
            x["_date"]=pd.to_datetime(x[datecol],errors="coerce")
            x["_close"]=pd.to_numeric(x[closecol],errors="coerce")
            x=x.dropna(subset=["_date","_close"]).sort_values("_date")
            x["_ticker"]=x[tickercol].astype(str) if tickercol else os.path.splitext(hist_file.name)[0]
            tickers=sorted(x["_ticker"].unique())
            selected=st.multiselect("Select stocks",tickers,default=tickers[:min(5,len(tickers))])
            x=x[x["_ticker"].isin(selected)].copy()
            if not x.empty:
                st.subheader("Historical closing prices")
                st.plotly_chart(px.line(x,x="_date",y="_close",color="_ticker",labels={"_date":"Date","_close":"Close price","_ticker":"Stock"}),use_container_width=True)
                x["_indexed"]=x.groupby("_ticker")["_close"].transform(lambda s:s/s.iloc[0]*100)
                st.subheader("Performance comparison (start = 100)")
                st.plotly_chart(px.line(x,x="_date",y="_indexed",color="_ticker",labels={"_date":"Date","_indexed":"Indexed value","_ticker":"Stock"}),use_container_width=True)
                rows=[]
                for ticker,g in x.groupby("_ticker"):
                    g=g.sort_values("_date")
                    if len(g)<2: continue
                    daily=g["_close"].pct_change().dropna()
                    yrs=max((g["_date"].iloc[-1]-g["_date"].iloc[0]).days/365.25,0.01)
                    total=(g["_close"].iloc[-1]/g["_close"].iloc[0]-1)*100
                    cagr=((g["_close"].iloc[-1]/g["_close"].iloc[0])**(1/yrs)-1)*100 if g["_close"].iloc[0]>0 else np.nan
                    vol=daily.std()*np.sqrt(252)*100 if len(daily)>1 else np.nan
                    dd=(g["_close"]/g["_close"].cummax()-1)*100
                    rows.append({"Stock":ticker,"Start date":g["_date"].min().date(),"End date":g["_date"].max().date(),"Rows":len(g),"Total return %":round(total,2),"Annualized return (CAGR) %":round(cagr,2),"Annualized volatility %":round(vol,2),"Max drawdown %":round(dd.min(),2)})
                if rows:
                    st.subheader("Historical risk and return")
                    st.dataframe(pd.DataFrame(rows),use_container_width=True,hide_index=True)
                st.caption("Metrics use the uploaded Close column. Historical results do not predict future performance.")
    except Exception as e:
        st.error(f"Could not read/analyse this CSV: {e}")
else:
    st.info("Upload your combined five-stock CSV here to view historical charts and risk/return metrics.")
st.divider()
st.caption("Prototype only: no live Zerodha connection, live market feed, LLM, MCP server, or trade execution.")
